/// Spacing tokens (logical pixels) calibrated to the 390×844 reference.
abstract final class Spacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 20;
  static const double xxl = 24;
  static const double xxxl = 32;
  static const double huge = 40;
  static const double massive = 48;

  /// Standard horizontal page padding.
  static const double pagePadding = 20;

  /// Card border radius.
  static const double cardRadius = 16;

  /// Button border radius.
  static const double buttonRadius = 16;

  /// Small badge radius.
  static const double badgeRadius = 12;

  /// Thick border width for cards/buttons.
  static const double borderWidth = 2.5;

  /// Thin border width for secondary outlines.
  static const double borderWidthThin = 1.5;
}
